"""
Draws the Coil icon (a mamba coiled round a £) and writes every file that uses it:
  build/icon.svg, build/icon.png (1024 px app icon, dark: navy tile, gold snake),
  web/components/brand-paths.ts (the same shapes for the in-app logo and favicon).
Run: python3 scripts/make-icon.py   (needs fontTools, Pillow and rsvg-convert; Inter Bold for the £)
"""
import math, os, subprocess, sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NAVY, GOLD = '#0F1A2E', '#D9C08E'
GOLD_LIGHT = '#F1E5C6'
R = 28  # ring radius, in a 100 x 100 box

def pt(a, r=R):
    t = math.radians(a); return (50 + r * math.sin(t), 50 - r * math.cos(t))

def body_path(start=14, end=340, w=11, span=114, tip=0.7):
    """The body: full width from the neck, then narrowing smoothly to a fine tail."""
    t0 = end - span
    def half(a):
        if a <= t0: return w / 2
        f = (a - t0) / span; f = f * f * (3 - 2 * f)
        return w / 2 + (tip - w / 2) * f
    angs = [start + i * (end - start) / 160 for i in range(161)]
    outer = [pt(a, R + half(a)) for a in angs]
    inner = [pt(a, R - half(a)) for a in reversed(angs)]
    d = 'M' + ' L'.join(f'{x:.2f} {y:.2f}' for x, y in outer + inner) + ' Z'
    return d

def head_path(at=7, rx=9.5, ry=7.4):
    """A mamba's head: long, flat, a little squared at the snout; pointing back along the ring at the tail."""
    x, y = pt(at)
    P = lambda fx, fy: f'{x + rx * fx:.2f} {y + ry * fy:.2f}'
    d = (f'M{P(-1, 0)} C{P(-1, -1)} {P(0.6, -1)} {P(0.9, -0.55)} '
         f'C{P(1.05, -0.35)} {P(1.05, 0.35)} {P(0.9, 0.55)} '
         f'C{P(0.6, 1)} {P(-1, 1)} {P(-1, 0)} Z')
    return d, f'rotate({at + 180:.1f} {x:.2f} {y:.2f})'

def eye(at=7):
    return pt(at - 3.5, R + 2.2)

def pound_path():
    font = None
    for f in ['/usr/share/fonts/opentype/inter/Inter-Bold.otf', '/Library/Fonts/Inter-Bold.otf']:
        if os.path.exists(f): font = TTFont(f); break
    if not font: sys.exit('Inter Bold not found')
    gs = font.getGlyphSet(); name = font.getBestCmap()[ord('£')]
    upm = font['head'].unitsPerEm; size = 36; s = size / upm
    adv = font['hmtx'][name][0] * s
    pen = SVGPathPen(gs, ntos=lambda v: f'{v:.2f}')
    gs[name].draw(TransformPen(pen, (s, 0, 0, -s, 50 - adv / 2, 63.5)))
    return pen.getCommands()

BODY = body_path(); HEAD, HEAD_T = head_path(); EX, EY = eye(); POUND = pound_path()

def svg(size, tile, snake, mark, inset=0):
    k = (size - 2 * inset) / 100
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 {size} {size}">'
            f'<g transform="translate({inset} {inset}) scale({k})">'
            f'<rect width="100" height="100" rx="22.4" fill="{tile}"/>'
            f'<path d="{BODY}" fill="{snake}"/><path d="{HEAD}" transform="{HEAD_T}" fill="{snake}"/>'
            f'<circle cx="{EX:.2f}" cy="{EY:.2f}" r="1.5" fill="{tile}"/>'
            f'<path d="{POUND}" fill="{mark}"/></g></svg>')

os.makedirs(os.path.join(ROOT, 'build'), exist_ok=True)
open(os.path.join(ROOT, 'build/icon.svg'), 'w').write(svg(1024, NAVY, GOLD, GOLD_LIGHT, inset=100))
subprocess.run(['rsvg-convert', '-w', '1024', '-h', '1024', os.path.join(ROOT, 'build/icon.svg'), '-o', os.path.join(ROOT, 'build/icon.png')], check=True)

open(os.path.join(ROOT, 'web/components/brand-paths.ts'), 'w').write(f'''// Generated by scripts/make-icon.py: the Coil mark in a 100 x 100 box. Don't edit by hand.
export const BODY = '{BODY}';
export const HEAD = '{HEAD}';
export const HEAD_TRANSFORM = '{HEAD_T}';
export const EYE = {{ cx: {EX:.2f}, cy: {EY:.2f} }};
export const POUND = '{POUND}';
''')
print('wrote build/icon.svg, build/icon.png, web/components/brand-paths.ts')
